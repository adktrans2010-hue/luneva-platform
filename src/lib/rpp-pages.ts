export const rppPages: Record<string, RppPageDefinition> = Object.fromEntries(
  Object.entries(rppPageContent).map(([slug, page]) => [
    slug,
    {
      ...page,
      status: getPublicationStatus(slug ? `/rpp/${slug}` : "/rpp"),
    },
  ]),
);

export function getRppSections(headings: string[]) {
  return headings
    .map((heading) => rppDocument.sections.find((section) => section.heading === heading))
    .filter((section): section is RppSection => Boolean(section));
}
